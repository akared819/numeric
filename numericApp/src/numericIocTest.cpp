static bool readDouble(const char* name, double& value) {
    DBADDR addr;
    long count = 1;
    return !dbNameToAddr(name, &addr) &&
           !dbGetField(&addr, DBR_DOUBLE, &value, nullptr, &count, nullptr) && count == 1;
}
